export function renderTablerIcon(name, cls='') {
  const paths = iconPaths[name] || iconPaths['map-pin'];
  return `<svg class="plan-tabler-icon ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths.join('')}</svg>`;
}

export function resolveTravelPointIcon(pointType) {
  return leisureIconMap.travelPoint[pointType] || leisureIconMap.travelPoint.default;
}

export function resolveSpotIcon(category) {
  return leisureIconMap.spotCategory[category] || leisureIconMap.spotCategory.default;
}

export function resolveDestinationIcon({pointType, category, role} = {}) {
  if (pointType) return resolveTravelPointIcon(pointType);
  if (category) return resolveSpotIcon(category);
  if (role && leisureIconMap.destinationRole[role]) return leisureIconMap.destinationRole[role];
  return leisureIconMap.spotCategory.default;
}

export function resolveTransferIcon(mode) {
  return leisureIconMap.transferMode[mode] || leisureIconMap.transferMode.default;
}

export function resolveContentIcon(role) {
  return leisureIconMap.contentRole[role] || 'map-pin';
}
